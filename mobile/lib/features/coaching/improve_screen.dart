class ImproveScreen extends StatelessWidget {
  const ImproveScreen({super.key, required this.state, required this.onOpenSettings, this.embedded = false});
  final AppState state;
  final VoidCallback onOpenSettings;
  final bool embedded; // inside the Stats tab, which supplies the title

  @override
  Widget build(BuildContext context) => ListenableBuilder(
        listenable: state,
        builder: (context, _) {
          final g = gate(context, state, onSetup: onOpenSettings);
          if (g != null) return g;
          final ops = state.activeOps;
          // RP history only describes ranked play, so ranked findings appear for All and Ranked views.
          final rankedView = state.mode == ModeFilter.all || state.mode == ModeFilter.ranked;
          final base = ops.isEmpty ? const <Insight>[] : buildInsights(ops, game: state.game, rp: rankedView ? state.rp : null, profile: state.profile);
          int rank(Tone t) => switch (t) { Tone.warn => 0, Tone.info => 1, Tone.good => 2 };
          final items = [...base, ...contextInsights(state.matchLog, state.noteFor), ...replayInsights([for (final r in state.replays) analyzeRound(r, state.playerName)])]..sort((a, b) => rank(a.tone).compareTo(rank(b.tone)));
          final tracking = {for (final g in state.goals) g.metric};
          final fix = items.where((i) => i.tone == Tone.warn).toList();
          final notes = items.where((i) => i.tone == Tone.info).toList();
          final strengths = items.where((i) => i.tone == Tone.good).toList();

          Widget card(Insight i) => Padding(
                padding: const EdgeInsets.only(bottom: 12),
                child: InsightCard(
                  i,
                  footer: (i.metric != null && !tracking.contains(i.metric) && state.snapshots.isNotEmpty)
                      ? Padding(
                          padding: const EdgeInsets.only(top: 10),
                          child: OutlinedButton.icon(onPressed: () => state.startGoal(i.metric!), icon: const Icon(Icons.flag_outlined, size: 18), label: const Text('Track this as a goal')),
                        )
                      : null,
                ),
              );

          return PageBody(state: state, children: [
            if (!embedded) const Padding(padding: EdgeInsets.fromLTRB(4, 8, 4, 4), child: Text('Improve', style: TextStyle(fontSize: 26, fontWeight: FontWeight.w900))),
            const Padding(padding: EdgeInsets.fromLTRB(4, 0, 4, 12), child: Text('Rule-based coaching from your own numbers. Each finding says how much data it rests on.', style: TextStyle(color: AppColors.textDim, height: 1.4))),
            FilterBar(state),
            if (ops.isEmpty) Padding(padding: const EdgeInsets.only(top: 16), child: state.loading ? const Skeleton(height: 140) : Notice('No ${state.filterLabel} data yet.', color: AppColors.textDim)),
            if (state.goals.isNotEmpty) ...[
              const SectionTitle('Your goals'),
              for (final g in state.goals) Padding(padding: const EdgeInsets.only(bottom: 12), child: _GoalCard(goal: g, state: state)),
            ],
            if (fix.isNotEmpty) ...[SectionTitle('Fix first', subtitle: '${fix.length} thing${fix.length == 1 ? '' : 's'} costing you the most'), ...fix.map(card)],
            if (notes.isNotEmpty) ...[const SectionTitle('Good to know'), ...notes.map(card)],
            if (strengths.isNotEmpty) ...[const SectionTitle('Strengths'), ...strengths.map(card)],
            const SectionTitle('How this works'),
            const AppCard(
              child: Text(
                'Findings are generated by fixed rules with minimum sample sizes, not guesses. They show correlation, not cause: map, teammates and opponents also affect results. '
                'Goals are measured only on rounds you play after you start them, using the snapshots the app saves when it refreshes.',
                style: TextStyle(color: AppColors.textDim, height: 1.45),
              ),
            ),
          ]);
        },
      );
}

class _GoalCard extends StatelessWidget {
  const _GoalCard({required this.goal, required this.state});
  final Goal goal;
  final AppState state;

  @override
  Widget build(BuildContext context) {
    final p = progressFor(goal, state.snapshots);
    final m = goal.metric;
    final span = goal.target - goal.baseline;
    final frac = (p.ready && span != 0) ? ((p.value! - goal.baseline) / span).clamp(0.0, 1.0) : 0.0;
    final done = p.ready && ((span >= 0 && p.value! >= goal.target) || (span < 0 && p.value! <= goal.target));
    return AppCard(
      child: Column(crossAxisAlignment: CrossAxisAlignment.start, children: [
        Row(children: [
          Expanded(child: Text(metricLabel(m), style: const TextStyle(fontWeight: FontWeight.w800, fontSize: 16))),
          if (done) const Pill('Reached', color: AppColors.good, icon: Icons.check),
          IconButton(visualDensity: VisualDensity.compact, tooltip: 'Stop tracking', onPressed: () => state.removeGoal(m), icon: const Icon(Icons.close, size: 18, color: AppColors.textDim)),
        ]),
        Row(children: [
          Text(formatMetric(m, goal.baseline), style: const TextStyle(color: AppColors.textDim, fontWeight: FontWeight.w700)),
          const Padding(padding: EdgeInsets.symmetric(horizontal: 8), child: Icon(Icons.arrow_forward, size: 14, color: AppColors.textDim)),
          Text(formatMetric(m, goal.target), style: const TextStyle(color: AppColors.accent, fontWeight: FontWeight.w900)),
          const Spacer(),
          Text(p.ready ? 'Now ${formatMetric(m, p.value!)}' : '${p.rounds}/$minGoalRounds rounds', style: const TextStyle(fontWeight: FontWeight.w800)),
        ]),
        const SizedBox(height: 10),
        ClipRRect(
          borderRadius: BorderRadius.circular(6),
          child: LinearProgressIndicator(value: p.ready ? frac : p.rounds / minGoalRounds, minHeight: 9, backgroundColor: AppColors.surfaceHi, valueColor: AlwaysStoppedAnimation(done ? AppColors.good : (p.ready ? AppColors.accent : AppColors.textDim))),
        ),
        const SizedBox(height: 8),
        Text(p.ready ? 'Measured over ${p.rounds} rounds since you started.' : 'Play ${minGoalRounds - p.rounds > 0 ? minGoalRounds - p.rounds : 0} more rounds and refresh to see progress.', style: const TextStyle(color: AppColors.textDim, fontSize: 12)),
      ]),
    );
  }
}
